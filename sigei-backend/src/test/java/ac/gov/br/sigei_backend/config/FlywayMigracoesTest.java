package ac.gov.br.sigei_backend.config;

import org.flywaydb.core.Flyway;
import org.flywaydb.core.api.output.MigrateResult;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.testcontainers.service.connection.ServiceConnection;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.ActiveProfiles;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;
import org.testcontainers.postgresql.PostgreSQLContainer;

import javax.sql.DataSource;
import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.Statement;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Executa as migrações do Flyway em um PostgreSQL real e confirma que o
 * Hibernate valida as entidades contra o esquema migrado. Requer Docker;
 * sem ele, os testes são ignorados.
 */
@SpringBootTest(properties = {
        "spring.flyway.enabled=true",
        "spring.jpa.hibernate.ddl-auto=validate",
        "spring.jpa.database-platform=org.hibernate.dialect.PostgreSQLDialect",
        "spring.datasource.driver-class-name=org.postgresql.Driver"
})
@ActiveProfiles("test")
@Testcontainers(disabledWithoutDocker = true)
class FlywayMigracoesTest {

    @Container
    @ServiceConnection
    static PostgreSQLContainer postgres = new PostgreSQLContainer("postgres:17-alpine");

    @Autowired JdbcTemplate jdbc;
    @Autowired DataSource dataSource;

    @Test
    void bancoNovoDeveReceberTodasAsMigracoesEValidarAsEntidades() {
        // O contexto só sobe se o Hibernate (ddl-auto=validate) aceitar o esquema migrado
        List<String> versoes = jdbc.queryForList(
                "select version from flyway_schema_history where success order by installed_rank", String.class);

        assertEquals(List.of("1", "2", "3", "4", "5", "6", "7", "8", "9"), versoes);
    }

    @Test
    void excluirUsuarioDeveApagarSeusRefreshTokens() {
        Long usuarioId = jdbc.queryForObject("""
                insert into usuario (nome, email, senha, perfil, ativo, alterar_senha)
                values ('Teste', 'exclusao-refresh@sigei.ac.gov.br', 'x', 'USUARIO', true, false) returning id
                """, Long.class);
        jdbc.update("""
                insert into refresh_token (usuario_id, token_hash, criado_em, expira_em, revogado)
                values (?, repeat('a', 64), now(), now() + interval '1 day', false)
                """, usuarioId);

        jdbc.update("delete from usuario where id = ?", usuarioId);

        assertEquals(0, jdbc.queryForObject(
                "select count(*) from refresh_token where usuario_id = ?", Integer.class, usuarioId));
    }

    @Test
    void bancoCriadoPeloHibernateDeveReceberBaselineEApenasAsNovasMigracoes() throws Exception {
        String schema = "legado_sem_refresh";
        criarSchema(schema, script("V1__esquema_inicial.sql"));

        MigrateResult resultado = flyway(schema).migrate();

        assertEquals(8, resultado.migrationsExecuted);
        assertEquals(List.of("BASELINE:1", "SQL:2", "SQL:3", "SQL:4", "SQL:5", "SQL:6", "SQL:7", "SQL:8", "SQL:9"), historico(schema));
        assertTrue(colunaExiste(schema, "refresh_token", "revogado_em"));
        assertTrue(chaveEstrangeiraExiste(schema, "fkpr5fysa08n2o6i1rxjumfl89q"));
    }

    @Test
    void bancoComRefreshTokenCriadoPeloHibernateDeveAceitarAMigracao() throws Exception {
        // Versão intermediária da tabela, sem revogado_em nem a chave estrangeira
        String schema = "legado_com_refresh";
        criarSchema(schema, script("V1__esquema_inicial.sql") + """
                create table refresh_token (
                    revogado boolean not null,
                    criado_em timestamp(6) with time zone not null,
                    expira_em timestamp(6) with time zone not null,
                    id bigint generated by default as identity,
                    usuario_id bigint not null,
                    token_hash varchar(64) not null unique,
                    primary key (id)
                );
                """);

        MigrateResult resultado = flyway(schema).migrate();

        assertEquals(8, resultado.migrationsExecuted);
        assertTrue(colunaExiste(schema, "refresh_token", "revogado_em"));
        assertTrue(chaveEstrangeiraExiste(schema, "fkpr5fysa08n2o6i1rxjumfl89q"));
    }

    @Test
    void vinculosDaTabelaAnexoDevemSerCopiadosParaEscolaSedeQuandoValidos() throws Exception {
        String schema = "legado_com_anexo";
        criarSchema(schema, script("V1__esquema_inicial.sql") + """
                insert into escola (id, nome, tipo_unidade, escola_sede_id) values
                    (1, 'Sede 1', 'SEDE', null),
                    (2, 'Anexo com um vinculo', 'ANEXO', null),
                    (3, 'Anexo com dois vinculos', 'ANEXO', null),
                    (4, 'Sede 4', 'SEDE', null),
                    (5, 'Anexo que ja tinha sede', 'anexo', 4),
                    (6, 'Sede apontada como anexo', 'SEDE', null),
                    (7, 'Anexo de um anexo', 'ANEXO', null);
                insert into anexo (escola_id, escola_anexo_id) values
                    (1, 2), (1, 3), (4, 3), (1, 5), (1, 6), (5, 7);
                """);

        flyway(schema).migrate();

        assertEquals(List.of("1:null", "2:1", "3:null", "4:null", "5:4", "6:null", "7:null"),
                jdbc.queryForList("select id || ':' || coalesce(escola_sede_id::text, 'null') from "
                        + schema + ".escola order by id", String.class));
        assertFalse(colunaExiste(schema, "anexo", "id"));

        // V4: o estado existente entra na revisão inicial da auditoria, atribuída ao sistema
        assertEquals(List.of("2:1:0", "5:4:0"), jdbc.queryForList(
                "select id || ':' || coalesce(escola_sede_id::text, 'null') || ':' || revtype from "
                        + schema + ".escola_aud where id in (2, 5) order by id", String.class));
        assertEquals(1, jdbc.queryForObject(
                "select count(*) from " + schema + ".revisao where usuario_id is null", Integer.class));
    }

    @Test
    void situacaoEAcessoDevemSerPadronizadosComAsOpcoesDoSistema() throws Exception {
        String schema = "legado_com_situacoes";
        criarSchema(schema, script("V1__esquema_inicial.sql") + """
                insert into infraestrutura_escola (id, situacao, tipo_acesso) values
                    (1, 'FUNCIONANDO', 'FLUVIAL'),
                    (2, 'PARALISADA', 'DESATIVADA'),
                    (3, ' paralisada ', 'Terrestre'),
                    (4, 'EXTINTA', 'AEREO'),
                    (5, '', null);
                """);

        flyway(schema).migrate();

        assertEquals(List.of("1:FUNCIONANDO:FLUVIAL", "2:PARALISADA:-", "3:PARALISADA:TERRESTRE", "4:-:-", "5:-:-"),
                jdbc.queryForList("select id || ':' || coalesce(situacao, '-') || ':' || coalesce(tipo_acesso, '-') from "
                        + schema + ".infraestrutura_escola order by id", String.class));

        // Revisão inicial (V4) com as 5 linhas e revisão do ajuste (V5) só com as alteradas
        assertEquals(List.of("1:0", "2:0", "2:1", "3:0", "3:1", "4:0", "4:1", "5:0", "5:1"),
                jdbc.queryForList("select id || ':' || revtype from " + schema
                        + ".infraestrutura_escola_aud order by id, rev", String.class));
        assertEquals(2, jdbc.queryForObject(
                "select count(*) from " + schema + ".revisao where usuario_id is null", Integer.class));
    }

    @Test
    void aguaEEnergiaDevemSerConvertidasParaAsOpcoesDoSistema() throws Exception {
        String schema = "legado_com_agua_energia";
        criarSchema(schema, script("V1__esquema_inicial.sql") + """
                insert into infraestrutura_escola (id, tipo_agua, tipo_energia) values
                    (1, 'POÇO', 'REDE ELETRICA'),
                    (2, 'RIO/VERTENTE', 'NÃO'),
                    (3, 'IGARAPÉ', 'SIM'),
                    (4, 'CACIMBA', 'SOLAR'),
                    (5, 'DESATIVADA', 'DESATIVADA'),
                    (6, 'VERTENTE', null);
                """);

        flyway(schema).migrate();

        assertEquals(List.of("1:POCO:REDE_PUBLICA", "2:RIO_VERTENTE:NAO", "3:IGARAPE:OUTRO",
                        "4:CACIMBA:SOLAR", "5:-:-", "6:VERTENTE:-"),
                jdbc.queryForList("select id || ':' || coalesce(tipo_agua, '-') || ':' || coalesce(tipo_energia, '-') from "
                        + schema + ".infraestrutura_escola order by id", String.class));

        // Linhas já válidas (4 e 6) não entram na revisão do ajuste
        assertEquals(List.of(1L, 2L, 3L, 5L), jdbc.queryForList(
                "select id from " + schema + ".infraestrutura_escola_aud where revtype = 1 order by id", Long.class));
    }

    @Test
    void emailsDeUsuarioDevemSerNormalizadosSemQuebrarDuplicados() throws Exception {
        String schema = "legado_com_emails";
        criarSchema(schema, script("V1__esquema_inicial.sql") + """
                insert into usuario (id, nome, email, senha, perfil, ativo, alterar_senha) values
                    (1, 'Já normalizado', 'ana@x.com', 's', 'USUARIO', true, false),
                    (2, 'Com maiúsculas', ' Joao@X.com ', 's', 'USUARIO', true, false),
                    (3, 'Duplicado A', 'maria@x.com', 's', 'USUARIO', true, false),
                    (4, 'Duplicado B', 'Maria@X.com', 's', 'USUARIO', true, false);
                """);

        flyway(schema).migrate();

        assertEquals(List.of("1:ana@x.com", "2:joao@x.com", "3:maria@x.com", "4:Maria@X.com"),
                jdbc.queryForList("select id || ':' || email from " + schema + ".usuario order by id", String.class));

        // Só o usuário 2 entra na revisão do ajuste
        assertEquals(List.of("2:joao@x.com"), jdbc.queryForList(
                "select id || ':' || email from " + schema + ".usuario_aud where revtype = 1", String.class));
    }

    @Test
    void aldeiaDevePoderTerMaisDeUmaEscolaDepoisDaMigracao() throws Exception {
        String schema = "legado_aldeia_unica";
        criarSchema(schema, script("V1__esquema_inicial.sql") + """
                insert into municipio (id, nome) values (1, 'Feijó');
                insert into terra_indigena (id, nome, municipio_id) values (1, 'Katukina/Kaxinawa', 1);
                insert into povo (id, nome) values (1, 'Huni Kui');
                insert into aldeia (id, nome, terra_indigena_id, povo_id) values (1, 'Belo Monte', 1, 1);
                insert into escola (id, codigo, nome, tipo_unidade, aldeia_id) values (1, '12031909', 'Primeira', 'SEDE', 1);
                """);

        flyway(schema).migrate();

        jdbc.update("insert into " + schema + ".escola (id, codigo, nome, tipo_unidade, aldeia_id) "
                + "values (2, '12004065', 'Segunda', 'SEDE', 1)");
        assertEquals(2, jdbc.queryForObject(
                "select count(*) from " + schema + ".escola where aldeia_id = 1", Integer.class));
        assertEquals(1, jdbc.queryForObject(
                "select count(*) from pg_indexes where schemaname = ? and indexname = 'idx_escola_aldeia'",
                Integer.class, schema));
    }

    private Flyway flyway(String schema) {
        return Flyway.configure()
                .dataSource(dataSource)
                .schemas(schema)
                .defaultSchema(schema)
                .createSchemas(false)
                .baselineOnMigrate(true)
                .baselineVersion("1")
                .locations("classpath:db/migration")
                .load();
    }

    private void criarSchema(String schema, String sql) throws Exception {
        try (Connection conexao = dataSource.getConnection(); Statement comando = conexao.createStatement()) {
            comando.execute("create schema " + schema);
            try {
                comando.execute("set search_path to " + schema);
                comando.execute(sql);
            } finally {
                comando.execute("set search_path to public");
            }
        }
    }

    private List<String> historico(String schema) {
        return jdbc.queryForList(
                "select type || ':' || version from " + schema + ".flyway_schema_history order by installed_rank",
                String.class);
    }

    private boolean colunaExiste(String schema, String tabela, String coluna) {
        Integer total = jdbc.queryForObject(
                "select count(*) from information_schema.columns where table_schema = ? and table_name = ? and column_name = ?",
                Integer.class, schema, tabela, coluna);
        return total != null && total == 1;
    }

    private boolean chaveEstrangeiraExiste(String schema, String nome) {
        Integer total = jdbc.queryForObject(
                "select count(*) from pg_constraint c join pg_namespace n on n.oid = c.connamespace "
                        + "where n.nspname = ? and c.conname = ? and c.contype = 'f'",
                Integer.class, schema, nome);
        return total != null && total == 1;
    }

    private static String script(String nome) throws Exception {
        return new ClassPathResource("db/migration/" + nome).getContentAsString(StandardCharsets.UTF_8);
    }
}
