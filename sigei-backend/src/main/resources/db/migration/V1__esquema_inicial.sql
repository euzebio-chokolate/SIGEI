-- Esquema inicial do SIGEI, idêntico ao gerado pelo Hibernate (ddl-auto=update)
-- antes da adoção do Flyway, inclusive nos nomes das constraints.
-- Bancos que já existiam são marcados como baseline na versão 1 e não executam
-- este script (spring.flyway.baseline-on-migrate); bancos novos o executam.

create table municipio (
    id bigint generated by default as identity,
    nome varchar(255),
    primary key (id)
);

create table terra_indigena (
    id bigint generated by default as identity,
    municipio_id bigint,
    nome varchar(255),
    primary key (id)
);

create table povo (
    id bigint generated by default as identity,
    nome varchar(255),
    primary key (id)
);

create table aldeia (
    id bigint generated by default as identity,
    povo_id bigint not null,
    terra_indigena_id bigint not null,
    nome varchar(255),
    primary key (id)
);

create table escola (
    aldeia_id bigint unique,
    escola_sede_id bigint,
    id bigint generated by default as identity,
    codigo varchar(255),
    nome varchar(255),
    tipo_unidade varchar(255),
    primary key (id)
);

create table anexo (
    escola_anexo_id bigint,
    escola_id bigint,
    id bigint generated by default as identity,
    primary key (id),
    unique (escola_id, escola_anexo_id)
);

create table ano_referencia (
    ano integer not null unique,
    id bigint generated by default as identity,
    primary key (id)
);

create table registro_anual (
    total_alunos integer,
    ano_referencia_id bigint,
    escola_id bigint,
    id bigint generated by default as identity,
    local_funcionamento varchar(255),
    rede varchar(255),
    primary key (id),
    unique (escola_id, ano_referencia_id)
);

create table equipe_escola (
    necessita_transporte boolean not null,
    tem_barqueiro boolean not null,
    tem_equipe_gestora boolean not null,
    tem_merendeira boolean not null,
    tem_professor_responsavel boolean not null,
    tem_zeladora boolean not null,
    ano_referencia_id bigint,
    id bigint generated by default as identity,
    registro_anual_id bigint unique,
    primary key (id)
);

create table infraestrutura_escola (
    ano_construcao integer,
    latitude float(53),
    longitude float(53),
    num_salas integer,
    tem_internet boolean,
    tem_predio boolean,
    tem_registro_fotografico boolean,
    id bigint generated by default as identity,
    registro_anual_id bigint unique,
    foto_public_id varchar(255),
    foto_url varchar(255),
    situacao varchar(255),
    tipo_acesso varchar(255),
    tipo_agua varchar(255),
    tipo_energia varchar(255),
    primary key (id)
);

create table matricula_nivel (
    qtd_feminino integer,
    qtd_masculino integer,
    total integer,
    id bigint generated by default as identity,
    registro_id bigint,
    nivel varchar(255),
    primary key (id)
);

create table matricula_serie (
    qtd_feminino integer,
    qtd_masculino integer,
    total integer,
    id bigint generated by default as identity,
    registro_id bigint,
    denominacao varchar(255),
    etapa_ensino varchar(255),
    primary key (id)
);

create table usuario (
    alterar_senha boolean default true not null,
    ativo boolean not null,
    id bigint generated by default as identity,
    email varchar(255) not null unique,
    nome varchar(255) not null,
    perfil varchar(255) not null check ((perfil in ('ADMIN','USUARIO'))),
    senha varchar(255) not null,
    primary key (id)
);

