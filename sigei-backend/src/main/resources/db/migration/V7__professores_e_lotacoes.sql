-- Professores e lotações (quadro de escolas e professores indígenas).
-- professor: dados pessoais. cpf e matricula são sensíveis e ficam cifrados pela
-- aplicação (AES-256-GCM, formato "v1:<Base64>"); cpf_hash é o índice cego do CPF
-- (HMAC-SHA256), usado na unicidade e na busca, e não é auditado.
-- lotacao_professor: onde o professor atua em cada ano. professor_id nulo = vaga em
-- aberto; escola_id nulo = lotação no núcleo de educação do município. numero_contrato
-- também é cifrado.
-- DDL idêntico ao gerado pelo Hibernate, inclusive nos nomes das constraints.

create table professor (
    sexo varchar(1),
    id bigint generated by default as identity,
    cpf_hash varchar(64),
    cpf varchar(255),
    etnia varchar(255),
    formacao varchar(255),
    matricula varchar(255),
    nome varchar(255) not null,
    primary key (id),
    constraint uk_professor_cpf_hash unique (cpf_hash)
);

create table lotacao_professor (
    inicio_contrato date,
    ano_referencia_id bigint not null,
    escola_id bigint,
    id bigint generated by default as identity,
    municipio_id bigint not null,
    professor_id bigint,
    amparo_legal varchar(255),
    cargo varchar(255),
    numero_contrato varchar(255),
    segmento varchar(255),
    tipo_contrato varchar(255),
    primary key (id)
);

alter table if exists lotacao_professor
    add constraint FKk9wbe0epo3qt472d5oixpuwko
    foreign key (ano_referencia_id) references ano_referencia;

alter table if exists lotacao_professor
    add constraint FKeambo28o97dl6jo6qbv8jgm9f
    foreign key (escola_id) references escola;

alter table if exists lotacao_professor
    add constraint FK9h9pibw45q10vb8g5mrul3ex3
    foreign key (municipio_id) references municipio;

alter table if exists lotacao_professor
    add constraint FK2efk3rq0pux8ku3kn0452bco5
    foreign key (professor_id) references professor;

-- Consultas por ano (tela de professores), por professor e pela exclusão de escola.
create index idx_lotacao_professor_ano on lotacao_professor (ano_referencia_id);
create index idx_lotacao_professor_professor on lotacao_professor (professor_id);
create index idx_lotacao_professor_escola on lotacao_professor (escola_id);

-- Trilha de auditoria (Envers). Os valores sensíveis também ficam cifrados aqui.
create table professor_aud (
    revtype smallint,
    sexo varchar(1),
    id bigint not null,
    rev bigint not null,
    cpf varchar(255),
    etnia varchar(255),
    formacao varchar(255),
    matricula varchar(255),
    nome varchar(255),
    primary key (id, rev)
);

create table lotacao_professor_aud (
    inicio_contrato date,
    revtype smallint,
    ano_referencia_id bigint,
    escola_id bigint,
    id bigint not null,
    municipio_id bigint,
    professor_id bigint,
    rev bigint not null,
    amparo_legal varchar(255),
    cargo varchar(255),
    numero_contrato varchar(255),
    segmento varchar(255),
    tipo_contrato varchar(255),
    primary key (id, rev)
);

alter table if exists professor_aud
    add constraint FKtovx9ce00tn96cm9rxw1hktox
    foreign key (rev) references revisao;

alter table if exists lotacao_professor_aud
    add constraint FKojbmw2g63t6kw6o7ul6v5a1k
    foreign key (rev) references revisao;
