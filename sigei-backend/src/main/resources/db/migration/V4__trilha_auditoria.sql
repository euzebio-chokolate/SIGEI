-- Revisão inicial, atribuída ao sistema: registra o estado dos dados existentes
-- antes da auditoria, para que a primeira alteração de cada um tenha os valores
-- anteriores. Autoria e datas anteriores a esta migração não são conhecidas.
insert into revisao (data_hora) values (now());

insert into municipio_aud (id, rev, revtype, nome)
select id, (select max(id) from revisao), 0, nome from municipio;

