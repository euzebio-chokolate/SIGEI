-- Trilha de auditoria (Hibernate Envers).
-- revisao: uma linha por transação que alterou entidades auditadas, com data/hora
-- e autor (copiado do usuário autenticado; nulo = sistema).
-- <entidade>_aud: os valores de cada versão; revtype 0 = criação, 1 = alteração,
-- 2 = exclusão. DDL idêntico ao gerado pelo Hibernate, inclusive nos nomes das FKs.

create table revisao (
    data_hora timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    usuario_id bigint,
    usuario_email varchar(255),
    usuario_nome varchar(255),
    primary key (id)
);

create table aldeia_aud (
    revtype smallint,
    id bigint not null,
    povo_id bigint,
    rev bigint not null,
    terra_indigena_id bigint,
    nome varchar(255),
    primary key (id, rev)
);

create table ano_referencia_aud (
    ano integer,
    revtype smallint,
    id bigint not null,
    rev bigint not null,
    primary key (id, rev)
);

create table equipe_escola_aud (
    necessita_transporte boolean,
    revtype smallint,
    tem_barqueiro boolean,
    tem_equipe_gestora boolean,
    tem_merendeira boolean,
    tem_professor_responsavel boolean,
    tem_zeladora boolean,
    ano_referencia_id bigint,
    id bigint not null,
    registro_anual_id bigint,
    rev bigint not null,
    primary key (id, rev)
);

create table escola_aud (
    revtype smallint,
    aldeia_id bigint,
    escola_sede_id bigint,
    id bigint not null,
    rev bigint not null,
    codigo varchar(255),
    nome varchar(255),
    tipo_unidade varchar(255),
    primary key (id, rev)
);

create table infraestrutura_escola_aud (
    ano_construcao integer,
    latitude float(53),
    longitude float(53),
    num_salas integer,
    revtype smallint,
    tem_internet boolean,
    tem_predio boolean,
    tem_registro_fotografico boolean,
    id bigint not null,
    registro_anual_id bigint,
    rev bigint not null,
    foto_public_id varchar(255),
    foto_url varchar(255),
    situacao varchar(255),
    tipo_acesso varchar(255),
    tipo_agua varchar(255),
    tipo_energia varchar(255),
    primary key (id, rev)
);

create table matricula_nivel_aud (
    qtd_feminino integer,
    qtd_masculino integer,
    revtype smallint,
    total integer,
    id bigint not null,
    registro_id bigint,
    rev bigint not null,
    nivel varchar(255),
    primary key (id, rev)
);

create table matricula_serie_aud (
    qtd_feminino integer,
    qtd_masculino integer,
    revtype smallint,
    total integer,
    id bigint not null,
    registro_id bigint,
    rev bigint not null,
    denominacao varchar(255),
    etapa_ensino varchar(255),
    primary key (id, rev)
);

create table municipio_aud (
    revtype smallint,
    id bigint not null,
    rev bigint not null,
    nome varchar(255),
    primary key (id, rev)
);

create table povo_aud (
    revtype smallint,
    id bigint not null,
    rev bigint not null,
    nome varchar(255),
    primary key (id, rev)
);

create table registro_anual_aud (
    revtype smallint,
    total_alunos integer,
    ano_referencia_id bigint,
    escola_id bigint,
    id bigint not null,
    rev bigint not null,
    local_funcionamento varchar(255),
    rede varchar(255),
    primary key (id, rev)
);

create table terra_indigena_aud (
    revtype smallint,
    id bigint not null,
    municipio_id bigint,
    rev bigint not null,
    nome varchar(255),
    primary key (id, rev)
);

create table usuario_aud (
    alterar_senha boolean,
    ativo boolean,
    revtype smallint,
    id bigint not null,
    rev bigint not null,
    email varchar(255),
    nome varchar(255),
    perfil varchar(255) check ((perfil in ('ADMIN','USUARIO'))),
    primary key (id, rev)
);

