-- Sessões renováveis (refresh tokens). Apenas o hash SHA-256 do token é gravado.
-- Idempotente: em bancos de desenvolvimento a tabela pode já ter sido criada pelo
-- Hibernate (ddl-auto=update) antes da adoção do Flyway.

create table if not exists refresh_token (
    revogado boolean not null,
    criado_em timestamp(6) with time zone not null,
    expira_em timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    revogado_em timestamp(6) with time zone,
    usuario_id bigint not null,
    token_hash varchar(64) not null unique,
    primary key (id)
);

alter table refresh_token add column if not exists revogado_em timestamp(6) with time zone;

do $$
begin
    if not exists (
        select 1 from pg_constraint
        where conname = 'fkpr5fysa08n2o6i1rxjumfl89q'
          and conrelid = 'refresh_token'::regclass
    ) then
        alter table refresh_token
            add constraint FKpr5fysa08n2o6i1rxjumfl89q
            foreign key (usuario_id) references usuario on delete cascade;
    end if;
end
$$;
